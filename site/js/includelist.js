// Upstream's plain-text include/exclude list format (0_custom_configuration/*.txt).
import { CATEGORY_RE } from "./catalog.js";

// Expand a list to module paths. `catalog` resolves directories and checks existence.
export function parseList(text, catalog) {
  const rels = new Set();
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.split("#")[0].trim().replace(/\\/g, "/").replace(/^\/+|\/+$/g, "");
    if (!line) continue;
    if (line.endsWith(".xml")) { if (catalog.exists(line)) rels.add(line); }
    else if (CATEGORY_RE.test(line)) for (const r of catalog.moduleRels(line)) rels.add(r);
  }
  return [...rels].sort();
}

export function formatList(profile, title = "Visual Sysmon Modular") {
  const lines = [`# Generated by ${title} – profile '${profile.name}'`, `# Sysmon version: ${profile.sysmon_version}`, ""];
  let current = null;
  for (const rel of [...profile.modules].sort()) {
    const cat = rel.split("/")[0];
    if (cat !== current) { lines.push("", `# ${cat}`); current = cat; }
    lines.push(rel);
  }
  return lines.join("\n") + "\n";
}
